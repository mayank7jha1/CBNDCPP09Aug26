#include<iostream>
using namespace std;

/*
	If you want to execute repeat statement iteratively:
	Keywords:
	1. While Loop
	2. For Loop
	3. Do while Loop
	4. For each loop

	Conditional Statements :
	1. If/else
	2. Ternary
	3. Switch


	Repeat Statements :
	1. Starting Point
	2. Ending Point
	3. Task
	4. Next State : Ek bar kaam karliya ab next bars kaam kaise karna hain.


	Jump Statements :
	1. Return
	2. Break
	3. Continue
*/


int main() {

	//Starting Point
	int c = 1;


	//Stopping Point:
	while (c <= 10) {

		//Task Done : One time:
		cout << c << " ";


		//Next State :
		c++;
	}

}